/** Rough wall area of a bathroom from its floor area: square-ish room, door subtracted. */
function wallArea(floor: number, height: number) {
  const perimeter = 4.2 * Math.sqrt(floor);
  return Math.max(4, Math.round((perimeter * height - 1.6) * 10) / 10);
}

